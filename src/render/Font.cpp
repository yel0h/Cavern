void Font::init()
{
    constexpr int ATLAS_W = ATLAS_COLS * CHAR_W;
    constexpr int ATLAS_H = ATLAS_ROWS * CHAR_H;
    std::vector<unsigned int> pixels(ATLAS_W * ATLAS_H, 0u);
    for (int ci = 0; ci < 128; ci++)
    {
        int col = ci & 0x0F;
        int row = ci >> 4;
        int baseX = col * CHAR_W;
        int baseY = row * CHAR_H;
        for (int y = 0; y < CHAR_H; y++)
        {
            unsigned char bits = glyphs[ci][CHAR_H - 1 - y];
            for (int x = 0; x < CHAR_W; x++)
            {
                bool lit = (bits >> (7 - x)) & 1;
                pixels[((baseY + y) * ATLAS_W) + (baseX + x)] = lit ? 0xFFFFFFFFu : 0u;
            }
        }
    }

    glGenTextures(1, &texId);
    glBindTexture(GL_TEXTURE_2D, texId);
    glTexImage2D(GL_TEXTURE_2D, 0, GL_RGBA, ATLAS_W, ATLAS_H, 0,
                 GL_RGBA, GL_UNSIGNED_BYTE, pixels.data());
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MIN_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_MAG_FILTER, GL_NEAREST);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_S, GL_CLAMP_TO_EDGE);
    glTexParameteri(GL_TEXTURE_2D, GL_TEXTURE_WRAP_T, GL_CLAMP_TO_EDGE);
    glBindTexture(GL_TEXTURE_2D, 0);
}

void Font::shutdown()
{
    if (texId)
    {
        glDeleteTextures(1, &texId);
        texId = 0;
    }
}

void Font::uvForChar(char c, float &u0, float &v0, float &u1, float &v1)
{
    int idx = c & 0x7F;
    int col = idx & 0x0F;
    int row = idx >> 4;
    constexpr float rw = 1.f / ATLAS_COLS;
    constexpr float rh = 1.f / ATLAS_ROWS;
    u0 = col * rw;
    u1 = (col + 1) * rw;
    v0 = row * rh;
    v1 = (row + 1) * rh;
}